// Helper function to get posts by category
export const getPostsByCategory = (category) => {
  if (category === "all") return mediaPosts;
  return mediaPosts.filter(post => post.category === category);
};

// Helper function to get featured post
export const getFeaturedPost = () => {
  return mediaPosts[0]; // Pehla wala featured hai
};

// Helper function to get related posts (same category, exclude current)
export const getRelatedPosts = (currentId, limit = 3) => {
  const current = mediaPosts.find(p => p.id === currentId);
  if (!current) return mediaPosts.slice(0, limit);
  
  const sameCategory = mediaPosts.filter(p => 
    p.category === current.category && p.id !== current.id
  );
  
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }
  
  // Agar same category mein kam hain toh mix karo
  const others = mediaPosts.filter(p => 
    p.category !== current.category && p.id !== current.id
  );
  
  return [...sameCategory, ...others].slice(0, limit);
};